#!/bin/sh
set -eu
TRACKER_API_PASSWORD="$(cat /run/secrets/runtime_password)"
export TRACKER_API_PASSWORD
psql --set=ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<'SQL'
\getenv runtime_password TRACKER_API_PASSWORD
CREATE ROLE tracker_api LOGIN PASSWORD :'runtime_password' NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS;
GRANT USAGE ON SCHEMA public TO tracker_api;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT,INSERT,UPDATE,DELETE ON TABLES TO tracker_api;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE,SELECT ON SEQUENCES TO tracker_api;
SQL
